-- Что агент СКАЗАЛ, а не что он сделал.
--
-- Ходы и вызовы инструментов записаны давно, и по ним видно, ЧТО произошло.
-- Почему - не видно: рассуждение живёт в транскриптах codex, файлами на диске,
-- в его собственном формате и без связи с нашими ходами.
--
-- Для страницы этого мало. Судья открывает адрес и должен увидеть не только
-- кривую капитала, но и решение словами: чем сессия обосновала вход, почему
-- отказалась, что нашла в цепочке. Разбирать ради этого чужой JSONL на каждый
-- запрос значило бы завести второй путь к данным и привязаться к формату,
-- который меняется вместе с codex. Харнесс же реплику и так держит в руках -
-- он её в чат отправляет.
--
-- Транскрипты остаются полной сырой записью для нашего разбора. Здесь - то, что
-- показывается.
create table if not exists said (
    id         bigserial primary key,
    turn_ref   text        not null,
    at         timestamptz not null default now(),
    text       text        not null
);

-- Читается это всегда одинаково: свежее сверху, и всё сказанное внутри хода.
create index if not exists said_at_idx on said (at desc);
create index if not exists said_turn_idx on said (turn_ref, at);
